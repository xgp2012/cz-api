// GetAdaptor returns a fresh adaptor for an API type, or nil when no built-in
// adaptor implements it.
//
// The channel type -> adaptor table lives in relay/providerregistry, the single
// registration point for built-in providers. Adding a provider is one line
// there; the API type of a channel and the adaptor that serves it cannot
// diverge. This function keeps the API-type entry point used by the relay
// handlers, which carry an API type rather than a channel type.
func GetAdaptor(apiType int) channel.Adaptor {
	entry, ok := providerregistry.LookupByAPIType(apiType)
	if !ok {
		return nil
	}
	return entry.NewAdaptor()
}

// GetAdaptorByChannelType returns the adaptor that serves a channel type, or nil
// when the type has no built-in adaptor: a plugin channel type, a retired slot,
// or an unassigned value.
func GetAdaptorByChannelType(channelType int) channel.Adaptor {
	entry, ok := providerregistry.Lookup(channelType)
	if !ok {
		return nil
	}
	return entry.NewAdaptor()
}

func GetTaskPlatform(c *gin.Context) constant.TaskPlatform {
	if pluginKey := c.GetString("task_plugin_key"); pluginKey != "" {
		return constant.TaskPlatform(pluginKey)
	}
	channelType := c.GetInt("channel_type")
	if channelType > 0 {
		return constant.TaskPlatform(strconv.Itoa(channelType))
	}
	return constant.TaskPlatform(c.GetString("platform"))
}

